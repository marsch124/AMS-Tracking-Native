// Generates App/Sources/TrackIcons.swift from the web app's js/icons.js (the SAME drawings).
import fs from 'node:fs';
const src = fs.readFileSync(process.argv[2], 'utf8');
const fn = new Function(src.replace("'use strict';", '') + '\nreturn {ICON_PATHS, ICON_NAMES_HABIT, ICON_KEYWORDS, EMOJI_TO_ICON};');
const { ICON_PATHS, ICON_NAMES_HABIT, ICON_KEYWORDS, EMOJI_TO_ICON } = fn();
ICON_PATHS.forkKnife = `
        <path d="M6.2 3.6 C6.2 5.2 6.3 6.8 6.3 8.4"/>
        <path d="M8.4 3.5 C8.4 5.2 8.5 6.8 8.4 8.5"/>
        <path d="M10.5 3.6 C10.5 5.2 10.5 6.8 10.4 8.4"/>
        <path d="M6.3 8.4 C6.4 10.2 7.3 11 8.4 11.1 C9.6 11 10.4 10.2 10.4 8.4"/>
        <path d="M8.4 11.1 C8.5 14.2 8.5 17.3 8.6 20.4"/>
        <path d="M16.3 20.4 C16.2 14.9 16.2 9.3 16.1 3.8 C18.4 5.2 19 9.2 18.6 12.4 C18 12.9 17.1 13.1 16.2 13"/>`;
const attr = (tag, name) => { const m = tag.match(new RegExp('\\b' + name + '="([^"]*)"')); return m ? m[1] : null; };
const f = n => +n.toFixed(2);
function ellipse(tag) {
  const cx = +attr(tag, 'cx'), cy = +attr(tag, 'cy'), rx = +attr(tag, 'rx'), ry = +attr(tag, 'ry');
  let ang = 0, ox = cx, oy = cy;
  const t = attr(tag, 'transform');
  if (t) { const m = t.match(/rotate\(([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\)/); if (m) { ang = +m[1] * Math.PI / 180; ox = +m[2]; oy = +m[3]; } }
  const rot = (x, y) => { const dx = x - ox, dy = y - oy; return [ox + dx * Math.cos(ang) - dy * Math.sin(ang), oy + dx * Math.sin(ang) + dy * Math.cos(ang)]; };
  const k = 0.5522847498;
  const P = (x, y) => rot(x, y).map(f).join(' ');
  return `M${P(cx + rx, cy)} C${P(cx + rx, cy + k * ry)} ${P(cx + k * rx, cy + ry)} ${P(cx, cy + ry)} C${P(cx - k * rx, cy + ry)} ${P(cx - rx, cy + k * ry)} ${P(cx - rx, cy)} C${P(cx - rx, cy - k * ry)} ${P(cx - k * rx, cy - ry)} ${P(cx, cy - ry)} C${P(cx + k * rx, cy - ry)} ${P(cx + rx, cy - k * ry)} ${P(cx + rx, cy)} Z`;
}
const out = [];
out.push('import Foundation', '', '// GENERATED by tools/make-icons.mjs from the web app\'s js/icons.js — the SAME hand-drawn icons, read with', '// AMSIcons\' SVG path reader. 24-point grid, stroke 1.7, round ends. Do not edit by hand; `forkKnife` is the', '// one drawing added here (the Stop Fasting mark, which the web app never needed).', '',
  'struct IconStroke { let d: String; let width: Double?; let surfaceFill: Bool }', '', 'enum TrackIcons {');
out.push('    static let strokes: [String: [IconStroke]] = [');
for (const [name, body] of Object.entries(ICON_PATHS)) {
  const parts = [];
  for (const tag of body.match(/<(path|ellipse)[^>]*\/>/g) || []) {
    const d = tag.startsWith('<path') ? attr(tag, 'd') : ellipse(tag);
    const w = attr(tag, 'stroke-width'); const fill = attr(tag, 'fill');
    parts.push(`IconStroke(d: "${d.replace(/\s+/g, ' ').trim()}", width: ${w ? w : 'nil'}, surfaceFill: ${fill && fill.includes('surface') ? 'true' : 'false'})`);
  }
  out.push(`        "${name}": [`, ...parts.map(p => `            ${p},`), '        ],');
}
out.push('    ]', '');
out.push('    /// The 40 icons a habit can have, in the picker\'s order.');
out.push('    static let habitNames = [' + ICON_NAMES_HABIT.map(n => `"${n}"`).join(', ') + ']', '');
out.push('    /// Search words per habit icon, English and German.');
out.push('    static let keywords: [String: String] = [');
for (const [k, v] of Object.entries(ICON_KEYWORDS)) out.push(`        "${k}": "${v}",`);
out.push('    ]', '');
out.push('    /// Emoji stored by the web app\'s first version → icon names.');
out.push('    static let emoji: [String: String] = [');
for (const [k, v] of Object.entries(EMOJI_TO_ICON)) out.push(`        "${k}": "${v}",`);
out.push('    ]', '}');
fs.writeFileSync(process.argv[3], out.join('\n') + '\n');
console.log(Object.keys(ICON_PATHS).length, 'icons');
